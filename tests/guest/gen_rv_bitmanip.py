#!/usr/bin/env python3
"""Generate rv_bitmanip.c: Zba / Zbb / Zbc / Zbs / Zicond instructions over edge-case
operands, hashed per instruction. Output must equal qemu-system-riscv64 -cpu max."""
tests = []
R = "sh1add sh2add sh3add add.uw sh1add.uw sh2add.uw sh3add.uw andn orn xnor min minu max maxu rol ror rolw rorw bclr bext binv bset clmul clmulh clmulr czero.eqz czero.nez".split()
U = "clz ctz cpop clzw ctzw cpopw sext.b sext.h zext.h rev8 orc.b".split()
I = {"slli.uw": (0, 1, 13, 63), "rori": (0, 1, 31, 63), "roriw": (0, 1, 17, 31), "bclri": (0, 1, 31, 63), "bexti": (0, 1, 31, 63),
     "binvi": (0, 1, 31, 63), "bseti": (0, 1, 31, 63)}
for m in R:
    tests.append((m.replace(".", "_"), f"{m} a0, a1, a2"))
for m in U:
    tests.append((m.replace(".", "_"), f"{m} a0, a1"))
for m, shs in I.items():
    for sh in shs:
        tests.append((f"{m.replace('.', '_')}_{sh}", f"{m} a0, a1, {sh}"))
out = ["// GENERATED by gen_rv_bitmanip.py -- do not edit.", r'''
typedef unsigned long u64;
#define UART ((volatile unsigned char *)0x10000000)
static void putc(char c) { *UART = c; }
static void puts(const char *s) { while (*s) putc(*s++); }
static void puthex(u64 v) { for (int i = 60; i >= 0; i -= 4) putc("0123456789abcdef"[(v >> i) & 15]); }
static u64 h;
static void mix(u64 v) { for (int i = 0; i < 8; i++) { h ^= (v >> (8 * i)) & 0xff; h *= 0x100000001b3UL; } }
static const u64 P[] = {
    0, 1, ~0UL, 0x8000000000000000UL, 0x7fffffffffffffffUL, 0x0123456789abcdefUL, 0xdeadbeefcafef00dUL,
    0x00ff00ff00ff00ffUL, 0x5555555555555555UL, 0xaaaaaaaaaaaaaaaaUL, 0x00000000ffffffffUL, 0xffffffff00000000UL,
    0x0000000100000001UL, 0x80000000UL, 0xffffffff80000000UL, 63, 64, 31, 32, 0x0000ffff0000ffffUL, 0x8001UL, 0xff80UL,
};
#define NP (sizeof P / sizeof P[0])
''']
for name, insn in tests:
    out.append(f'''static void t_{name}(void) {{
 for (unsigned i = 0; i < NP; i++) for (unsigned j = 0; j < NP; j++) {{ u64 r;
  asm volatile("mv a1, %1\\n mv a2, %2\\n {insn}\\n mv %0, a0" : "=r"(r) : "r"(P[i]), "r"(P[j]) : "a0", "a1", "a2");
  mix(r); }} }}''')
out.append("struct t { const char *name; void (*fn)(void); };\nstatic const struct t tests[] = {")
for name, _ in tests:
    out.append(f'    {{"{name}", t_{name}}},')
out.append("};")
out.append(r'''
int main(void) {
    u64 all = 0;
    for (unsigned k = 0; k < sizeof tests / sizeof tests[0]; k++) {
        h = 0xcbf29ce484222325UL;
        tests[k].fn();
        puts(tests[k].name); putc(' '); puthex(h); putc('\n');
        all ^= h * (k + 1);
    }
    puts("all "); puthex(all); putc('\n');
    return 0;
}
''')
open("rv_bitmanip.c", "w").write("\n".join(out))
print(len(tests), "tests")
